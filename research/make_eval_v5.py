#!/usr/bin/env python3
"""Merge the v5-vi question fragments and split them into a dev and a frozen held-out file.

    python -m research.make_eval_v5 --fragment docs/upgrade/scratch/q5_w1.yaml \
        --fragment docs/upgrade/scratch/q5_w2.yaml --fragment docs/upgrade/scratch/q5_w3.yaml

Same stratified split as v4 (fixed seed) plus the v5 rules: the whole pool is validated with
`--strict-v5` (category, `lang` vi or mixed, honest `diacritics` flag) and cross-checked against
every v4 file, so a re-used question can never be split across the two halves. The script prints
counts per (category, lang), the number of questions written without diacritics per split, the
minimum-count checks, and the SHA-256 of each output; it never prints a question, because the
held-out half must stay blind after it is frozen.
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

import yaml

from . import make_eval_v4, validate_eval_set

REPO = Path(__file__).resolve().parents[1]
SEED = 20261026
DEV_RATIO = 0.4
MIN_QUESTIONS = 110
MIN_DIACRITICS_FREE = 0.40
V4_SETS = ["tests/eval_v4_dev.yaml", "tests/eval_v4_heldout.yaml", "tests/eval_v4_neg_vi.yaml"]
CATEGORY_TARGETS = {"param": 20, "code": 20, "protocol": 15, "hwdef": 10, "wiki": 20,
                    "elrs_edgetx": 10, "troubleshoot": 10, "negative": 15}

DEV_HEADER = """\
# Eval set v5-vi, DEV split: tunable, treated like tests/golden.yaml. Generated by
# research/make_eval_v5.py from the writer fragments; do not hand-edit, re-merge instead.
"""
HELDOUT_HEADER = """\
# Eval set v5-vi, HELD-OUT split: frozen by docs/eval-v5-vi-heldout.sha256.
# Nobody opens this file to read questions; run it only through
# `python -m research.eval_retrieval --set tests/eval_v5_vi_heldout.yaml --aggregate-only`.
# Tuning against it is forbidden; re-merge only before the freeze.
"""


def no_diacritics(rows: list[dict]) -> int:
    return sum(1 for row in rows if row.get("diacritics") is False)


def write_set(path: Path, rows: list[dict], header: str, split_name: str) -> str:
    body = yaml.safe_dump({"version": 5, "generated_by": "research.make_eval_v5", "seed": SEED,
                           "split": split_name, "questions": rows},
                          allow_unicode=True, sort_keys=False, width=100)
    path.write_bytes((header + body).encode("utf-8"))
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--fragment", action="append", required=True)
    parser.add_argument("--dev", default=str(REPO / "tests" / "eval_v5_vi_dev.yaml"))
    parser.add_argument("--heldout", default=str(REPO / "tests" / "eval_v5_vi_heldout.yaml"))
    parser.add_argument("--ratio", type=float, default=DEV_RATIO)
    args = parser.parse_args(argv)

    questions = make_eval_v4.load_fragments([Path(name) for name in args.fragment])
    ids = [str(question.get("id")) for question in questions]
    duplicated = {value for value in ids if ids.count(value) > 1}
    if duplicated:
        print(f"duplicate ids: {len(duplicated)}", file=sys.stderr)
        return 2
    # Validate the whole pool BEFORE splitting: a cross-fragment or cross-set duplicate must never
    # end up with one copy in dev and one in the held-out half.
    report = validate_eval_set.validate(questions, None, strict_v5=True)
    others = [(Path(name).name, question) for name in V4_SETS
              for question in validate_eval_set.load_questions(REPO / name)]
    report["errors"].extend(validate_eval_set.cross_overlap_errors(questions, others))
    if report["errors"]:
        print(f"fragment validation failed: {len(report['errors'])} error(s) "
              f"({len(others)} v4 questions cross-checked)", file=sys.stderr)
        for error in report["errors"][:25]:
            detail = f" {error['detail']}" if error["detail"] else ""
            print(f"  - id={error['id']} code={error['code']}{detail}", file=sys.stderr)
        return 2

    dev, heldout = make_eval_v4.split(questions, ratio=args.ratio)
    dev_counts, heldout_counts = make_eval_v4.counts(dev), make_eval_v4.counts(heldout)

    print(f"fragments={len(args.fragment)} questions={len(questions)} "
          f"dev={len(dev)} heldout={len(heldout)} cross-checked={len(others)}")
    print(f"{'category':<14}{'lang':<8}{'dev':>5}{'heldout':>9}{'total':>7}")
    for key in sorted(set(dev_counts) | set(heldout_counts)):
        dev_n, heldout_n = dev_counts.get(key, 0), heldout_counts.get(key, 0)
        print(f"{key[0]:<14}{key[1]:<8}{dev_n:>5}{heldout_n:>9}{dev_n + heldout_n:>7}")

    print(f"\n{'category':<14}{'total':>6}{'target':>8}  check")
    totals: dict[str, int] = {}
    for question in questions:
        category = str(question.get("category") or "-")
        totals[category] = totals.get(category, 0) + 1
    for category, target in CATEGORY_TARGETS.items():
        print(f"{category:<14}{totals.get(category, 0):>6}{target:>8}  "
              f"{'ok' if totals.get(category, 0) >= target else 'SHORT'}")

    free_dev, free_heldout = no_diacritics(dev), no_diacritics(heldout)
    free_total = free_dev + free_heldout
    share = free_total / len(questions) if questions else 0.0
    print(f"\nno diacritics: total={free_total} ({share:.1%}) dev={free_dev} heldout={free_heldout}"
          f"  {'ok' if share >= MIN_DIACRITICS_FREE else 'SHORT'} (floor {MIN_DIACRITICS_FREE:.0%})")
    print(f"negatives: {totals.get('negative', 0)}  "
          f"{'ok' if totals.get('negative', 0) >= 15 else 'SHORT'} (floor 15)")

    dev_sha = write_set(Path(args.dev), dev, DEV_HEADER, "dev")
    heldout_sha = write_set(Path(args.heldout), heldout, HELDOUT_HEADER, "heldout")
    print(f"\nsha256 {Path(args.dev).name} = {dev_sha}")
    print(f"sha256 {Path(args.heldout).name} = {heldout_sha}")

    short = (len(questions) < MIN_QUESTIONS or share < MIN_DIACRITICS_FREE
             or totals.get("negative", 0) < 15)
    return 2 if short else 0


if __name__ == "__main__":
    sys.exit(main())
