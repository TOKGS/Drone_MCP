#!/usr/bin/env python3
"""Merge the v4 question fragments and split them into a dev and a frozen held-out file.

    python -m research.make_eval_v4 --fragment docs/upgrade/scratch/q_b1.yaml \
        --fragment docs/upgrade/scratch/q_b2.yaml --fragment docs/upgrade/scratch/q_b3.yaml \
        --dev tests/eval_v4_dev.yaml --heldout tests/eval_v4_heldout.yaml

The split is stratified by (category, lang) with a fixed seed, so it is reproducible. The script
prints only counts per stratum and the SHA-256 of each output file; it never prints a question,
because the held-out half must stay blind after it is frozen.
"""

from __future__ import annotations

import argparse
import hashlib
import random
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
SEED = 20261026
DEV_RATIO = 0.4

DEV_HEADER = """\
# Eval set v4, DEV split: tunable, treated like tests/golden.yaml. Generated by
# research/make_eval_v4.py from the writer fragments; do not hand-edit, re-merge instead.
"""
HELDOUT_HEADER = """\
# Eval set v4, HELD-OUT split: frozen by docs/eval-v4-heldout.sha256.
# Nobody opens this file to read questions; run it only through
# `python -m research.eval_retrieval --set tests/eval_v4_heldout.yaml --aggregate-only`.
# Tuning against it is forbidden; re-merge only before the freeze.
"""


def load_fragments(paths: list[Path]) -> list[dict]:
    questions: list[dict] = []
    for path in paths:
        payload = yaml.safe_load(path.read_text(encoding="utf-8"))
        if isinstance(payload, dict):
            payload = payload.get("questions")
        if not isinstance(payload, list):
            raise SystemExit(f"{path.name}: no `questions` list")
        questions.extend(payload)
    return questions


def _bucket(question: dict) -> tuple[str, str]:
    return str(question.get("category") or "-"), str(question.get("lang") or "-")


def split(questions: list[dict], *, ratio: float = DEV_RATIO,
          seed: int = SEED) -> tuple[list[dict], list[dict]]:
    """Stratified split: every (category, lang) bucket keeps its proportion in both halves."""
    buckets: dict[tuple[str, str], list[dict]] = {}
    for question in questions:
        buckets.setdefault(_bucket(question), []).append(question)
    dev: list[dict] = []
    heldout: list[dict] = []
    for key in sorted(buckets):
        rows = sorted(buckets[key], key=lambda item: str(item.get("id")))
        random.Random(f"{seed}:{key[0]}:{key[1]}").shuffle(rows)
        if len(rows) == 1:
            dev.extend(rows)
            continue
        take = max(1, min(len(rows) - 1, round(len(rows) * ratio)))
        dev.extend(rows[:take])
        heldout.extend(rows[take:])
    return dev, heldout


def counts(rows: list[dict]) -> dict[tuple[str, str], int]:
    counted: dict[tuple[str, str], int] = {}
    for question in rows:
        key = _bucket(question)
        counted[key] = counted.get(key, 0) + 1
    return counted


def write_set(path: Path, rows: list[dict], header: str, split_name: str) -> str:
    body = yaml.safe_dump({"version": 4, "generated_by": "research.make_eval_v4", "seed": SEED,
                           "split": split_name, "questions": rows},
                          allow_unicode=True, sort_keys=False, width=100)
    path.write_text(header + body, encoding="utf-8")
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--fragment", action="append", required=True)
    parser.add_argument("--dev", default=str(REPO / "tests" / "eval_v4_dev.yaml"))
    parser.add_argument("--heldout", default=str(REPO / "tests" / "eval_v4_heldout.yaml"))
    parser.add_argument("--ratio", type=float, default=DEV_RATIO)
    args = parser.parse_args(argv)

    questions = load_fragments([Path(name) for name in args.fragment])
    ids = [str(question.get("id")) for question in questions]
    duplicated = {value for value in ids if ids.count(value) > 1}
    if duplicated:
        print(f"duplicate ids: {len(duplicated)}", file=sys.stderr)
        return 2
    dev, heldout = split(questions, ratio=args.ratio)

    dev_counts, heldout_counts = counts(dev), counts(heldout)
    print(f"fragments={len(args.fragment)} questions={len(questions)} "
          f"dev={len(dev)} heldout={len(heldout)}")
    print(f"{'category':<14}{'lang':<8}{'dev':>5}{'heldout':>9}{'total':>7}")
    for key in sorted(set(dev_counts) | set(heldout_counts)):
        dev_n, heldout_n = dev_counts.get(key, 0), heldout_counts.get(key, 0)
        print(f"{key[0]:<14}{key[1]:<8}{dev_n:>5}{heldout_n:>9}{dev_n + heldout_n:>7}")

    dev_sha = write_set(Path(args.dev), dev, DEV_HEADER, "dev")
    heldout_sha = write_set(Path(args.heldout), heldout, HELDOUT_HEADER, "heldout")
    print(f"\nsha256 {Path(args.dev).name} = {dev_sha}")
    print(f"sha256 {Path(args.heldout).name} = {heldout_sha}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
